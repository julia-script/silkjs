#!/usr/bin/env python3
"""Compile CLDR default numbering systems into src/intl_default_numbering_data.silk.

The input is the unpacked `cldr-numbers-full` npm package (its `package/` directory). Rerun it
when CLDR is updated:

    python3 scripts/generate_intl_default_numbering.py path/to/cldr-numbers-full/package
"""
import argparse
import hashlib
import json
from pathlib import Path


def literal(data):
    return 'b"' + ''.join(f'\\x{byte:02x}' for byte in data) + '"'


def generate(package):
    main = package / 'main'
    version = json.loads((package / 'package.json').read_text())['version']
    locales = sorted(path.name for path in main.iterdir() if (path / 'numbers.json').is_file())
    digest = hashlib.sha256()
    systems = []
    table = bytearray()
    for locale in locales:
        source = (main / locale / 'numbers.json').read_bytes()
        digest.update(source)
        system = json.loads(source)['main'][locale]['numbers']['defaultNumberingSystem']
        if system not in systems:
            systems.append(system)
        table.append(systems.index(system))
    lines = [
        '// Generated by scripts/generate_intl_default_numbering.py; do not edit.',
        f'// CLDR {version} (cldr-numbers-full npm package): main/*/numbers.json.',
        f'// Source SHA-256 (files concatenated in locale order): {digest.hexdigest()}',
        '// CLDR data: Unicode License V3, https://www.unicode.org/license.txt',
        '//! Tables read by `intl_default_numbering`.',
        '',
        f'pub const CLDR_VERSION: string = "{version}"',
        '/// Locale identifiers in CLDR spelling, sorted, NUL-separated.',
        "pub fn locales() -> &'static [u8] {",
        '  return ' + literal('\0'.join(locales).encode()),
        '}',
        '/// One index into `SYSTEMS` per locale.',
        "pub fn table() -> &'static [u8] {",
        '  return ' + literal(table),
        '}',
        f'pub const SYSTEMS: [string; {len(systems)}] = [' + ', '.join(f'"{name}"' for name in systems) + ']',
        '',
    ]
    return '\n'.join(lines)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('package', type=Path, help='the cldr-numbers-full npm package directory')
    parser.add_argument('--output', type=Path, default=Path(__file__).resolve().parents[1] / 'src/intl_default_numbering_data.silk')
    args = parser.parse_args()
    args.output.write_text(generate(args.package))
