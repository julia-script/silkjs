#!/usr/bin/env python3
"""Compile CLDR flexible day periods into src/intl_day_period_data.silk.

The inputs are the unpacked `cldr-core` npm package (its supplemental dayPeriods.json holds
the rules: which hours each language's periods such as morning1 and afternoon2 cover) and
`cldr-dates-full` (each locale's format names for those periods, from ca-gregorian.json).
`intl_day_period` picks the period of an hour and its name for the `B` pattern field and the
`dayPeriod` option. Midnight is left out: ICU never formats it.
Rerun it when CLDR is updated:

    python3 scripts/generate_intl_day_periods.py path/to/cldr-core/package path/to/cldr-dates-full/package
"""
import argparse
import hashlib
import json
from pathlib import Path

PERIODS = ['noon', 'morning1', 'morning2', 'afternoon1', 'afternoon2', 'evening1', 'evening2', 'night1', 'night2']
WIDTHS = ['abbreviated', 'wide', 'narrow']


def literal(data):
    return 'b"' + ''.join(f'\\x{byte:02x}' for byte in data) + '"'


def hour(text):
    hours, minutes = text.split(':')
    if minutes != '00':
        raise ValueError(f'day period boundary off the hour: {text}')
    return int(hours)


def generate(core, dates):
    version = json.loads((dates / 'package.json').read_text())['version']
    digest = hashlib.sha256()
    source = (core / 'supplemental/dayPeriods.json').read_bytes()
    digest.update(source)
    rules = json.loads(source)['supplemental']['dayPeriodRuleSet']
    languages = sorted(rules)
    ruleBlob = bytearray()
    for language in languages:
        record = bytearray()
        count = 0
        for key, rule in rules[language].items():
            if key not in PERIODS:
                continue
            index = PERIODS.index(key)
            if '_at' in rule:
                record += bytes([index, hour(rule['_at']), hour(rule['_at']) + 1, 1])
            else:
                record += bytes([index, hour(rule['_from']), hour(rule['_before']), 0])
            count += 1
        ruleBlob += bytes([count]) + record
    ruleOffsets = bytearray()
    at = 0
    for language in languages:
        ruleOffsets += at.to_bytes(2, 'little')
        at += 1 + ruleBlob[at] * 4

    main = dates / 'main'
    locales = sorted(path.name for path in main.iterdir() if (path / 'ca-gregorian.json').is_file())
    pool = bytearray()
    strings = {}

    def text(value):
        if value not in strings:
            strings[value] = len(pool)
            pool.extend(value.encode() + b'\0')
        return strings[value]

    names = bytearray()
    seen = {}
    table = bytearray()
    for locale in locales:
        data = (main / locale / 'ca-gregorian.json').read_bytes()
        digest.update(data)
        periods = json.loads(data)['main'][locale]['dates']['calendars']['gregorian']['dayPeriods']['format']
        record = bytearray()
        for width in WIDTHS:
            for key in PERIODS:
                value = periods.get(width, {}).get(key)
                record += (0xFFFF if value is None else text(value)).to_bytes(2, 'little')
        record = bytes(record)
        if record not in seen:
            seen[record] = len(names)
            names += record
        table += seen[record].to_bytes(2, 'little')
    if len(pool) >= 0xFFFF or len(names) >= 0xFFFF:
        raise ValueError('day period tables outgrew 16-bit offsets')
    lines = [
        '// Generated by scripts/generate_intl_day_periods.py; do not edit.',
        f'// CLDR {version} (cldr-core supplemental/dayPeriods.json, cldr-dates-full main/*/ca-gregorian.json).',
        f'// Source SHA-256 (rules, then locales in order): {digest.hexdigest()}',
        '// CLDR data: Unicode License V3, https://www.unicode.org/license.txt',
        '//! Tables read by `intl_day_period`. Offsets are little-endian u16.',
        '',
        f'pub const PERIOD_COUNT: usize = {len(PERIODS)}',
        '/// Languages with day period rules, sorted, NUL-separated.',
        "pub fn languages() -> &'static [u8] {",
        '  return ' + literal('\0'.join(languages).encode()),
        '}',
        '/// The offset of each language\'s rules in `rules()`.',
        "pub fn ruleOffsets() -> &'static [u8] {",
        '  return ' + literal(ruleOffsets),
        '}',
        '/// Per language: a rule count, then per rule the period index (noon, morning1, morning2,',
        '/// afternoon1, afternoon2, evening1, evening2, night1, night2), its first hour, the hour',
        '/// it ends before (24 for midnight), and 1 when it holds only at the hour (noon).',
        "pub fn rules() -> &'static [u8] {",
        '  return ' + literal(ruleBlob),
        '}',
        '/// Locale identifiers in CLDR spelling, sorted, NUL-separated.',
        "pub fn locales() -> &'static [u8] {",
        '  return ' + literal('\0'.join(locales).encode()),
        '}',
        '/// The offset of each locale\'s record in `names()`.',
        "pub fn table() -> &'static [u8] {",
        '  return ' + literal(table),
        '}',
        '/// Per record: offsets into `strings()` of the abbreviated, wide and narrow names of each',
        '/// period, 0xffff where the locale has none.',
        "pub fn names() -> &'static [u8] {",
        '  return ' + literal(names),
        '}',
        '/// UTF-8 texts, NUL-terminated.',
        "pub fn strings() -> &'static [u8] {",
        '  return ' + literal(pool),
        '}',
        '',
    ]
    return '\n'.join(lines)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('core', type=Path, help='the cldr-core npm package directory')
    parser.add_argument('dates', type=Path, help='the cldr-dates-full npm package directory')
    parser.add_argument('--output', type=Path, default=Path(__file__).resolve().parents[1] / 'src/intl_day_period_data.silk')
    args = parser.parse_args()
    args.output.write_text(generate(args.core, args.dates))
