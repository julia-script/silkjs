'use strict';
// Real OpenSSL-generated peers. Run with the native runtime; OPENSSL may select
// an OpenSSL 3 executable (Homebrew's default is used on macOS).
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const crypto = require('node:crypto');
const openssl = process.env.OPENSSL || (process.platform === 'darwin' ? '/opt/homebrew/opt/openssl@3/bin/openssl' : 'openssl');
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'silk-certificates-'));
function run(...args) {
  const result = spawnSync(openssl, args, { cwd: dir, encoding: 'utf8' });
  if (result.error) throw result.error;
  assert.equal(result.status, 0, result.stderr);
  return result.stdout;
}
function read(name) { return fs.readFileSync(path.join(dir, name)); }
try {
  run('req', '-x509', '-newkey', 'rsa:2048', '-nodes', '-keyout', 'root.key', '-out', 'root.pem', '-subj', '/O=Silk Runtime/CN=Certificate Root', '-days', '2', '-addext', 'basicConstraints=critical,CA:TRUE', '-addext', 'keyUsage=critical,keyCertSign,cRLSign');
  run('req', '-new', '-newkey', 'rsa:2048', '-nodes', '-keyout', 'leaf.key', '-out', 'leaf.csr', '-subj', '/O=Silk Runtime/CN=fallback.example.test');
  fs.writeFileSync(path.join(dir, 'extensions.cnf'), 'basicConstraints=critical,CA:FALSE\nkeyUsage=digitalSignature,keyEncipherment\nextendedKeyUsage=serverAuth,clientAuth\nsubjectAltName=DNS:*.example.test,email:peer@example.test,IP:127.0.0.1,IP:::1,URI:https://example.test/path\nauthorityInfoAccess=OCSP;URI:http://ocsp.example.test,caIssuers;URI:http://ca.example.test/root.pem\n');
  run('x509', '-req', '-in', 'leaf.csr', '-CA', 'root.pem', '-CAkey', 'root.key', '-set_serial', '4660', '-days', '1', '-extfile', 'extensions.cnf', '-out', 'leaf.pem');
  run('x509', '-in', 'leaf.pem', '-outform', 'DER', '-out', 'leaf.der');
  const cert = new crypto.X509Certificate(read('leaf.pem'));
  const root = new crypto.X509Certificate(read('root.pem'));
  const key = crypto.createPrivateKey(read('leaf.key'));
  assert.ok(cert instanceof crypto.X509Certificate);
  const der = read('leaf.der');
  assert.deepEqual(cert.raw, der);
  assert.equal(new crypto.X509Certificate(new DataView(der.buffer, der.byteOffset, der.byteLength)).serialNumber, '1234');
  assert.equal(new crypto.X509Certificate(cert.raw).toString(), cert.toString());
  assert.equal(cert.toJSON(), cert.toString());
  assert.equal(JSON.parse(JSON.stringify(cert)), cert.toString());
  assert.match(cert.subject, /CN=fallback\.example\.test/);
  assert.match(cert.issuer, /CN=Certificate Root/);
  assert.equal(cert.issuerCertificate, undefined);
  assert.equal(cert.ca, false); assert.equal(root.ca, true);
  assert.equal(cert.serialNumber, '1234');
  assert.equal(cert.signatureAlgorithm, 'sha256WithRSAEncryption');
  assert.equal(cert.signatureAlgorithmOid, '1.2.840.113549.1.1.11');
  assert.equal(cert.validFromDate.getTime(), Date.parse(cert.validFrom));
  assert.equal(cert.validToDate.getTime(), Date.parse(cert.validTo));
  assert.deepEqual(cert.keyUsage, ['1.3.6.1.5.5.7.3.1', '1.3.6.1.5.5.7.3.2']);
  assert.match(cert.subjectAltName, /IP Address:0:0:0:0:0:0:0:1/);
  assert.match(cert.infoAccess, /OCSP - URI:http:\/\/ocsp\.example\.test/);
  for (const [property, digest] of [['fingerprint', 'sha1'], ['fingerprint256', 'sha256'], ['fingerprint512', 'sha512']]) {
    assert.equal(cert[property], crypto.createHash(digest).update(cert.raw).digest('hex').toUpperCase().match(/../g).join(':'));
  }
  assert.equal(cert.publicKey.type, 'public'); assert.equal(cert.publicKey, cert.publicKey);
  assert.equal(cert.checkHost('www.example.test'), '*.example.test');
  assert.equal(cert.checkHost('www.example.test', { wildcards: false }), undefined);
  assert.equal(cert.checkHost('a.b.example.test'), undefined);
  assert.equal(cert.checkHost('a.b.example.test', { multiLabelWildcards: true }), '*.example.test');
  assert.equal(cert.checkHost('fallback.example.test', { subject: 'always', wildcards: false }), 'fallback.example.test');
  assert.equal(cert.checkHost('fallback.example.test', { subject: 'never', wildcards: false }), undefined);
  assert.equal(cert.checkEmail('peer@example.test'), 'peer@example.test');
  assert.equal(cert.checkEmail('other@example.test'), undefined);
  assert.equal(cert.checkIP('127.0.0.1'), '127.0.0.1'); assert.equal(cert.checkIP('::1'), '::1');
  assert.equal(cert.checkIP('127.0.0.2'), undefined);
  assert.equal(cert.checkIssued(root), true); assert.equal(root.checkIssued(cert), false);
  assert.equal(cert.checkPrivateKey(key), true); assert.equal(root.checkPrivateKey(key), false);
  assert.equal(cert.verify(root.publicKey), true); assert.equal(cert.verify(cert.publicKey), false);
  assert.throws(() => cert.verify(key), { code: 'ERR_INVALID_ARG_VALUE' });
  assert.throws(() => cert.checkPrivateKey(cert.publicKey), { code: 'ERR_INVALID_ARG_VALUE' });
  assert.throws(() => cert.checkHost('x', { wildcards: 1 }), { code: 'ERR_INVALID_ARG_TYPE' });
  assert.throws(() => cert.checkHost('a\0b'), { code: 'ERR_INVALID_ARG_VALUE' });
  assert.throws(() => cert.checkIP('not an IP'), { code: 'ERR_INVALID_ARG_VALUE' });
  assert.throws(() => cert.checkIssued({}), { code: 'ERR_INVALID_ARG_TYPE' });
  assert.throws(() => new crypto.X509Certificate(new ArrayBuffer(1)), { code: 'ERR_INVALID_ARG_TYPE' });
  const legacy = cert.toLegacyObject();
  assert.equal(Object.getPrototypeOf(legacy.subject), null);
  assert.equal(legacy.subject.CN, 'fallback.example.test'); assert.equal(legacy.issuer.CN, 'Certificate Root');
  assert.equal(legacy.bits, 2048); assert.equal(legacy.exponent, '0x10001');
  assert.deepEqual(legacy.pubkey, cert.publicKey.export({ type: 'spki', format: 'der' }));
  assert.equal(legacy.modulus, Buffer.from(cert.publicKey.export({ format: 'jwk' }).n, 'base64url').toString('hex').toUpperCase());
  assert.deepEqual(legacy.infoAccess['OCSP - URI'], ['http://ocsp.example.test']);
  assert.deepEqual(legacy.ext_key_usage, cert.keyUsage); assert.deepEqual(legacy.raw, cert.raw);
  run('req', '-x509', '-newkey', 'ec', '-pkeyopt', 'ec_paramgen_curve:P-256', '-nodes', '-keyout', 'ec.key', '-out', 'ec.pem', '-subj', '/CN=EC Peer', '-days', '1');
  const ec = new crypto.X509Certificate(read('ec.pem'));
  const ecLegacy = ec.toLegacyObject();
  assert.equal(ecLegacy.asn1Curve, 'prime256v1'); assert.equal(ecLegacy.nistCurve, 'P-256');
  assert.equal(ecLegacy.bits, 256); assert.equal(ecLegacy.pubkey.length, 65); assert.equal(ecLegacy.pubkey[0], 4);
  assert.equal(ec.verify(ec.publicKey), true);
  const spkac = run('spkac', '-key', 'leaf.key', '-challenge', 'silk-real-challenge').trim().replace(/^SPKAC=/, '');
  assert.equal(crypto.Certificate.verifySpkac(spkac), true);
  assert.equal(crypto.Certificate().verifySpkac(spkac), true);
  assert.equal(crypto.Certificate.exportChallenge(spkac).toString(), 'silk-real-challenge');
  assert.deepEqual(crypto.createPublicKey(crypto.Certificate.exportPublicKey(spkac)).export({ type: 'spki', format: 'der' }), legacy.pubkey);
  assert.equal(crypto.Certificate.verifySpkac('not SPKAC'), false);
  assert.equal(crypto.Certificate.exportPublicKey('not SPKAC'), '');
  assert.equal(crypto.Certificate.exportChallenge('not SPKAC'), '');
  const broken = Buffer.from(spkac, 'base64'); broken[broken.length - 1] ^= 1;
  assert.equal(crypto.Certificate.verifySpkac(broken.toString('base64')), false);
  run('pkcs12', '-export', '-inkey', 'leaf.key', '-in', 'leaf.pem', '-certfile', 'root.pem', '-passout', 'pass:secret', '-out', 'bundle.p12');
  const bundle = read('bundle.p12');
  const parsed = crypto.parsePKCS12(bundle, { passphrase: Buffer.from('secret') });
  assert.equal(parsed.privateKey.type, 'private'); assert.ok(parsed.certificate instanceof crypto.X509Certificate);
  assert.deepEqual(parsed.certificate.raw, cert.raw); assert.equal(parsed.certificate.checkPrivateKey(parsed.privateKey), true);
  assert.equal(parsed.additionalCertificates.length, 1); assert.deepEqual(parsed.additionalCertificates[0].raw, root.raw);
  assert.equal(parsed.certificate.verify(parsed.additionalCertificates[0].publicKey), true);
  assert.throws(() => crypto.parsePKCS12(bundle, { passphrase: 'wrong' }));
  assert.throws(() => crypto.parsePKCS12(bundle, { passphrase: 'secret\0ignored' }), { code: 'ERR_INVALID_ARG_VALUE' });
  assert.throws(() => crypto.parsePKCS12('not bytes'), { code: 'ERR_INVALID_ARG_TYPE' });
  run('pkcs12', '-export', '-nokeys', '-in', 'root.pem', '-passout', 'pass:', '-out', 'certs.p12');
  const only = crypto.parsePKCS12(read('certs.p12'));
  assert.equal(only.privateKey, null); assert.equal(only.certificate, null);
  assert.equal(only.additionalCertificates.length, 1);
  assert.deepEqual(only.additionalCertificates[0].raw, root.raw);
  console.log('crypto certificates smoke passed');
} finally { fs.rmSync(dir, { recursive: true, force: true }); }
