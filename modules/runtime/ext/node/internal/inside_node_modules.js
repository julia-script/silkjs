'use strict';

// internalBinding('util').isInsideNodeModules from Node's src/node_util.cc: whether the
// nearest caller that is not a built-in (node:) runs from a node_modules directory.
// Node uses it to keep deprecation warnings out of dependencies. When the search
// would look past frameLimit frames it gives up with defaultValue.
const host = require('internal/host');

function isInsideNodeModules(frameLimit = 10, defaultValue = false) {
  const frames = host.captureCallSites(frameLimit, isInsideNodeModules);
  for (let index = 0; index < frames.length; index++) {
    const name = frames[index].scriptName;
    if (typeof name !== 'string' || name.length === 0 || name.startsWith('node:') || name.startsWith('silk:')) continue;
    return /[\\/]node_modules[\\/]/.test(name);
  }
  return frames.length < frameLimit ? false : defaultValue;
}

module.exports = { isInsideNodeModules };
