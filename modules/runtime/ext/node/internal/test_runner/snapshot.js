'use strict';

const { mkdirSync, readFileSync, writeFileSync } = require('fs');
const { dirname } = require('path');
const { strictEqual } = require('assert');
const { runInNewContext } = require('vm');
const missingTip = 'Missing snapshots can be generated by rerunning the command with the --test-update-snapshots flag.';
let serializers = [value => JSON.stringify(value, null, 2)];
let resolvePath = file => typeof file === 'string' ? `${file}.snapshot` : file;
function invalid(name, type) {
  return Object.assign(new TypeError(`The "${name}" argument must be ${type}.`), { code: 'ERR_INVALID_ARG_TYPE' });
}
function state(message, fields) { return Object.assign(new Error(message), { code: 'ERR_INVALID_STATE' }, fields); }
function functions(value, name) {
  if (!Array.isArray(value)) throw invalid(name, 'an Array');
  for (let index = 0; index < value.length; index++) if (typeof value[index] !== 'function') throw invalid(`${name}[${index}]`, 'a function');
}
function configuration(options) {
  if (options === null || typeof options !== 'object' || Array.isArray(options)) throw invalid('options', 'an object');
  const { serializers: selected = serializers } = options;
  functions(selected, 'options.serializers');
  return selected;
}
function escape(value) { return String(value).replaceAll('\\', '\\\\').replaceAll('`', '\\`').replaceAll('${', '\\${'); }
function key(value) { return JSON.stringify(value).slice(1, -1).replaceAll('`', '\\`').replaceAll('${', '\\${'); }
function serialize(input, selected, template) {
  try {
    let value = input;
    for (let index = 0; index < selected.length; index++) { const fn = selected[index]; value = fn(value); }
    return template ? `\n${escape(value)}\n` : value;
  } catch (cause) {
    throw state('The provided serializers did not generate a string.', { input, cause });
  }
}
function read(filename) {
  try { return readFileSync(filename, 'utf8'); }
  catch (cause) { throw readError(filename, cause); }
}
function readError(filename, cause) {
  return state(`Cannot read snapshot file '${filename}.'${cause?.code === 'ENOENT' ? ' ' + missingTip : ''}`, { filename, cause });
}
function write(filename, value) {
  try { mkdirSync(dirname(filename), { recursive: true }); writeFileSync(filename, value, 'utf8'); }
  catch (cause) { throw state(`Cannot write snapshot file '${filename}.'`, { filename, cause }); }
}
class SnapshotManager {
  constructor(update) { this.update = update; this.files = new Map(); }
  file(entry) {
    let file = this.files.get(entry);
    if (!file) {
      const filename = resolvePath(entry);
      if (typeof filename !== 'string') throw state('Invalid snapshot filename.', { filename });
      file = { filename, values: Object.create(null), counts: new Map(), loaded: this.update };
      this.files.set(entry, file);
    }
    return file;
  }
  snapshot(context, actual, options = {}) {
    const selected = configuration(options);
    const file = this.file(context.filePath);
    const value = serialize(actual, selected, true);
    const count = file.counts.get(context.fullName) || 1;
    file.counts.set(context.fullName, count + 1);
    const id = `${context.fullName} ${count}`;
    if (this.update) { file.values[key(id)] = value; return; }
    if (!file.loaded) {
      try {
        const scope = { __proto__: null, exports: Object.create(null) };
        runInNewContext(readFileSync(file.filename, 'utf8'), scope);
        if (scope.exports === null || typeof scope.exports !== 'object') throw state(`Malformed snapshot file '${file.filename}'.`);
        for (const name in scope.exports) file.values[name] = escape(scope.exports[name]);
        file.loaded = true;
      } catch (cause) { throw readError(file.filename, cause); }
    }
    if (!(id in file.values)) throw state(`Snapshot '${id}' not found in '${file.filename}.' ${missingTip}`, { snapshot: id, filename: file.filename });
    strictEqual(value, file.values[id]);
  }
  fileSnapshot(actual, filename, options = {}) {
    if (typeof filename !== 'string') throw invalid('path', 'a string');
    const value = serialize(actual, configuration(options), false);
    if (this.update) write(filename, value);
    else strictEqual(value, read(filename));
  }
  writeFiles() {
    if (!this.update) return;
    for (const file of this.files.values()) {
      const source = Object.keys(file.values).sort().map(name => `exports[\`${name}\`] = \`${file.values[name]}\`;\n`).join('\n');
      write(file.filename, source);
    }
  }
}
module.exports = {
  SnapshotManager,
  setDefaultSnapshotSerializers(value) { functions(value, 'serializers'); serializers = value.slice(); },
  setResolveSnapshotPath(fn) { if (typeof fn !== 'function') throw invalid('fn', 'a function'); resolvePath = fn; },
};
