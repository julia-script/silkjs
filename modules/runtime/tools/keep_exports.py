#!/usr/bin/env python3
"""Writes src/ext/keep_exports.silk and the `keepExports` function at the end of each module with
top-level C exports.

Silk emits a dependency's `export "C"` function only when Silk code takes it as a value, and
native code in the runtime's archives calls many of them by name. `runtime.embed.start` calls
`keep_exports.all()`, so a program that embeds the runtime links them. Run it after adding or
changing an export: python3 tools/keep_exports.py

An export that takes a function pointer cannot be taken as a value, so it is left out; nothing
in the archives calls one of those.
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "src"
MARK = "// Generated by tools/keep_exports.py; do not edit below."
CALLBACK = re.compile(r'^(?:pub )?type ([A-Za-z_0-9]+) = .*\bfn\(', re.M)
EXPORT = re.compile(r'^(?:pub )?(?:unsafe )?export "C" fn ([A-Za-z_0-9]+)\(')


def split_top(text):
    parts, depth, current = [], 0, ""
    for index, char in enumerate(text):
        if char in "<([":
            depth += 1
        elif char in ")]" or (char == ">" and text[index - 1] != "-"):
            depth -= 1
        if char == "," and depth == 0:
            parts.append(current)
            current = ""
        else:
            current += char
    if current.strip():
        parts.append(current)
    return parts


def signature(text, start):
    """The function type of the export whose parameter list opens at `start`."""
    depth, index = 0, start
    while True:
        if text[index] == "(":
            depth += 1
        elif text[index] == ")":
            depth -= 1
            if depth == 0:
                break
        index += 1
    params = [part.split(":", 1)[1].strip() for part in split_top(text[start + 1:index])]
    rest = text[index + 1:]
    end = min(position for position in (rest.find(" as \""), rest.find("{")) if position >= 0)
    result = rest[:end].strip()
    result = result[2:].strip() if result.startswith("->") else "()"
    return "extern \"C\" fn(" + ", ".join(params) + ") -> " + result


def main():
    modules = []
    callbacks = set()
    for path in SOURCE.rglob("*.silk"):
        if path.name != "embedded.silk":
            callbacks.update(CALLBACK.findall(path.read_text()))
    for path in sorted(SOURCE.rglob("*.silk")):
        if path.name in ("keep_exports.silk", "embedded.silk", "embed_smoke.silk"):
            continue
        text = path.read_text()
        if MARK in text:
            text = text[:text.index(MARK)].rstrip("\n") + "\n"
        lines = []
        offset = 0
        for line in text.splitlines(keepends=True):
            found = EXPORT.match(line)
            if found:
                name = found.group(1)
                kind = signature(text, offset + found.end() - 1)
                inner = kind[len('extern "C" fn('):]
                if "fn(" not in inner and not callbacks.intersection(re.findall(r"[A-Za-z_0-9]+", inner)):
                    lines.append("  let _%s: %s = %s" % (name, kind, name))
            offset += len(line)
        if lines:
            text += "\n" + MARK + "\n/// Takes each C export as a value, so that Silk emits it (see tools/keep_exports.py).\npub fn keepExports() -> () {\n" + "\n".join(lines) + "\n}\n"
            modules.append(".".join(path.relative_to(SOURCE).with_suffix("").parts))
        path.write_text(text)
    out = ["// Generated by tools/keep_exports.py; do not edit.",
           "//! Keeps the runtime's C exports in a program that links it as a dependency.", ""]
    out += ["import %s" % module for module in modules]
    out += ["", "/// Calls every module's `keepExports`.", "pub fn all() -> () {"]
    out += ["  %s.keepExports()" % module.rsplit(".", 1)[1] for module in modules]
    out += ["}", ""]
    (SOURCE / "ext" / "keep_exports.silk").write_text("\n".join(out))


main()
