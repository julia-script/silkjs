// Writes ext/node/internal/options_table.js from the reference Node's own option tables.
// usage: node --expose-internals tools/gen_node_options.js path/to/node_options.cc > ext/node/internal/options_table.js
// node_options.cc must be the same release as the node running this script (its Implies()
// declarations are not exposed at run time).
'use strict';
const fs = require('fs');
const { internalBinding } = require('internal/test/binding');
const binding = internalBinding('options');
const { options, aliases } = binding.getCLIOptionsInfo();
const typeNames = Object.fromEntries(Object.entries(binding.types).map(([name, value]) => [value, name.slice(1)]));
const implications = [];
const source = fs.readFileSync(process.argv[2], 'utf8');
for (const match of source.matchAll(/Implies\(\s*"([^"]+)",\s*"([^"]+)"\s*\)/g)) implications.push([match[1], match[2]]);
// Options of PerProcessOptionsParser apply to the whole process: a Worker's
// parser (per isolate) does not know them.
const processStart = source.indexOf('PerProcessOptionsParser::PerProcessOptionsParser(');
const processEnd = source.indexOf('\n}\n', processStart);
const perProcess = new Set();
for (const match of source.slice(processStart, processEnd).matchAll(/AddOption\(\s*"([^"]+)"/g)) perProcess.add(match[1]);
const out = [];
out.push(`// Generated by tools/gen_node_options.js from Node.js ${process.version}: do not edit.`);
out.push(`// Each option: [type, allowed in NODE_OPTIONS, default is true, process-wide].`);
out.push(`'use strict';`);
out.push('');
out.push('const options = new Map([');
for (const [name, info] of [...options].sort((a, b) => a[0] < b[0] ? -1 : 1))
  out.push(`  [${JSON.stringify(name)}, [${JSON.stringify(typeNames[info.type])}, ${info.envVarSettings === binding.envSettings.kAllowedInEnvvar}, ${info.defaultIsTrue}, ${perProcess.has(name)}]],`);
out.push(']);');
out.push('const aliases = new Map([');
for (const [name, expansion] of [...aliases].sort((a, b) => a[0] < b[0] ? -1 : 1))
  out.push(`  [${JSON.stringify(name)}, ${JSON.stringify(expansion)}],`);
out.push(']);');
out.push('const implications = [');
for (const pair of implications) out.push(`  ${JSON.stringify(pair)},`);
out.push('];');
out.push('');
out.push('module.exports = { options, aliases, implications };');
process.stdout.write(out.join('\n') + '\n');
