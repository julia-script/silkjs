#!/usr/bin/env python3
"""Compile CLDR Gregorian date and time patterns into src/intl_date_skeleton_data.silk.

The input is the unpacked `cldr-dates-full` npm package (its `package/` directory). Each locale
gets its dateFormats and timeFormats (the dateStyle and timeStyle patterns) and its
availableFormats skeleton-to-pattern table, which `intl_date_skeleton` matches requested
Intl.DateTimeFormat fields against. Where CLDR has an `-alt-ascii` form, it is used: it spells
the space before AM/PM as U+0020 rather than U+202F, as V8 and Node do for web compatibility.
Other alternates, plural (`-count-`) entries, and skeletons with quarter or week fields are left
out: Intl.DateTimeFormat never asks for them.
Rerun it when CLDR is updated:

    python3 scripts/generate_intl_date_skeletons.py path/to/cldr-dates-full/package
"""
import argparse
import hashlib
import json
from pathlib import Path


def literal(data):
    return 'b"' + ''.join(f'\\x{byte:02x}' for byte in data) + '"'


def generate(package):
    main = package / 'main'
    version = json.loads((package / 'package.json').read_text())['version']
    locales = sorted(path.name for path in main.iterdir() if (path / 'ca-gregorian.json').is_file())
    digest = hashlib.sha256()
    pool = bytearray()
    strings = {}

    def text(value):
        if value not in strings:
            strings[value] = len(pool)
            pool.extend(value.encode() + b'\0')
        return strings[value]

    sets = bytearray()
    setIndex = {}
    table = bytearray()
    styleTable = bytearray()
    for locale in locales:
        source = (main / locale / 'ca-gregorian.json').read_bytes()
        digest.update(source)
        gregorian = json.loads(source)['main'][locale]['dates']['calendars']['gregorian']
        formats = gregorian['dateTimeFormats']['availableFormats']
        entries = sorted((skeleton, formats.get(skeleton + '-alt-ascii', pattern)) for skeleton, pattern in formats.items()
                         if '-' not in skeleton and not set(skeleton) & set('QwW'))
        styles = bytearray()
        for kind in ['dateFormats', 'timeFormats']:
            for length in ['full', 'long', 'medium', 'short']:
                pattern = gregorian[kind].get(length + '-alt-ascii', gregorian[kind][length])
                # A few locales attach a numbering override: {"_value": pattern, "_numbers": ...}.
                if isinstance(pattern, dict):
                    pattern = pattern['_value']
                styles += text(pattern).to_bytes(2, 'little')
        styleTable += styles
        entry = bytearray([len(entries)])
        for skeleton, pattern in entries:
            entry += text(skeleton).to_bytes(2, 'little') + text(pattern).to_bytes(2, 'little')
        entry = bytes(entry)
        if entry not in setIndex:
            setIndex[entry] = len(sets)
            sets.extend(entry)
        table += setIndex[entry].to_bytes(3, 'little')
    if len(pool) >= 0xFFFF:
        raise ValueError('skeleton strings outgrew 16-bit offsets')
    lines = [
        '// Generated by scripts/generate_intl_date_skeletons.py; do not edit.',
        f'// CLDR {version} (cldr-dates-full npm package): main/*/ca-gregorian.json.',
        f'// Source SHA-256 (files concatenated in locale order): {digest.hexdigest()}',
        '// CLDR data: Unicode License V3, https://www.unicode.org/license.txt',
        '//! Tables read by `intl_date_skeleton`.',
        '',
        f'pub const CLDR_VERSION: string = "{version}"',
        f'pub const LOCALE_COUNT: usize = {len(locales)}',
        '/// Locale identifiers in CLDR spelling, sorted, NUL-separated.',
        "pub fn locales() -> &'static [u8] {",
        '  return ' + literal('\0'.join(locales).encode()),
        '}',
        '/// One little-endian u24 offset into `sets()` per locale.',
        "pub fn table() -> &'static [u8] {",
        '  return ' + literal(table),
        '}',
        '/// Eight little-endian u16 offsets into `strings()` per locale: the full, long, medium and',
        '/// short date patterns, then the time patterns.',
        "pub fn styles() -> &'static [u8] {",
        '  return ' + literal(styleTable),
        '}',
        '/// Per set: an entry count, then per entry u16 offsets of the skeleton and its pattern in',
        '/// `strings()`.',
        "pub fn sets() -> &'static [u8] {",
        '  return ' + literal(sets),
        '}',
        '/// UTF-8 texts, NUL-terminated.',
        "pub fn strings() -> &'static [u8] {",
        '  return ' + literal(pool),
        '}',
        '',
    ]
    return '\n'.join(lines)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('package', type=Path, help='the cldr-dates-full npm package directory')
    parser.add_argument('--output', type=Path, default=Path(__file__).resolve().parents[1] / 'src/intl_date_skeleton_data.silk')
    args = parser.parse_args()
    args.output.write_text(generate(args.package))
