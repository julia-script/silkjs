#!/usr/bin/env python3
"""Transcribe pinned QuickJS timezone tables, without consulting host tzdata."""
import argparse
import hashlib
import pathlib
import re
import struct

REVISION = '7d1c13c5d8f8c6b32893786ed35cdcebd88194d2'


def literal(data):
    return 'b"' + ''.join('\\x%02x' % b for b in data) + '"'


def generate(source):
    text = source.read_text()
    transitions = {}
    for name, body in re.findall(r'static const TZTransition (\w+)\[\] = \{(.*?)\n\};', text, re.S):
        transitions[name] = [(int(t.replace('LL', '')) if t != 'INT64_MIN' else -(1 << 63), int(o))
                             for t, o in re.findall(r'\{\s*(INT64_MIN|-?\d+LL),\s*(-?\d+)\s*\}', body)]
    def section(name):
        return re.search(r'\b' + name + r'\[\] = \{(.*?)\n\};', text, re.S).group(1)
    zones = re.findall(r'\{ "([^"]+)", (\w+), (\d+) \}', section('ti_tz_zone_data'))
    aliases = re.findall(r'\{ "([^"]+)", (\d+) \}', section('ti_tz_aliases'))
    names = re.findall(r'"([^"]+)"', section('ti_tz_names'))
    regions = re.findall(r'\{ "([^"]+)", "([^"]+)" \}', section('ti_tz_region_tab'))
    out = ['// Generated by scripts/generate_temporal_timezone.py; do not edit.',
           '// QuickJS ' + REVISION + '; LICENSE.quickjs.',
           '// Source SHA-256: ' + hashlib.sha256(source.read_bytes()).hexdigest(),
           '// Exact pinned table cutoffs; no host timezone database or extrapolation.',
           'import silk.collections.slice { Slice }', 'import silk.num.u8', 'import silk.num.i32', 'import silk.num.i64', '']
    for name, count in [('zone', len(zones)), ('alias', len(aliases)), ('name', len(names)), ('region', len(regions))]:
        out.append(f'pub const ti_tz_{name}_count: i32 = {count}')
    out += ['', 'fn read16(data: &[u8], at: usize) -> usize {',
            '  return u8.toUsize(data[at]) + u8.toUsize(data[at + 1]) * 256', '}',
            'fn readSigned64(data: &[u8], at: usize) -> i64 {',
            '  let mut high = u8.toI64(data[at + 7])',
            '  if high >= 128 { high = high - 256 }',
            '  let mut value = high', '  let mut i: usize = 7',
            '  while i > 0 { i = i - 1 value = value * 256 + u8.toI64(data[at + i]) }',
            '  return value', '}', '']
    def strings(fn, entries):
        data = bytearray()
        offsets = [0]
        for value in entries:
            data.extend(value.replace('\\000', '\0').encode('ascii'))
            offsets.append(len(data))
        assert len(data) < 65536
        out.extend([f"pub fn {fn}(index: i32) -> &'static [u8] {{",
                    '  let offsets = ' + literal(b''.join(struct.pack('<H', n) for n in offsets)),
                    '  let data = ' + literal(data),
                    '  let at = i32.toUsize(index) * 2',
                    '  let start = read16(offsets, at)',
                    '  return Slice.view<u8>(data, start, read16(offsets, at + 2) - start)', '}', ''])
    strings('tzZoneName', [z[0] for z in zones])
    strings('tzAliasName', [a[0] for a in aliases])
    strings('tzName', names)
    strings('tzRegionName', [r[0] for r in regions])
    strings('tzRegionZones', [r[1] for r in regions])
    def ints(fn, entries):
        out.extend([f'pub fn {fn}(index: i32) -> i32 {{',
                    '  let data = ' + literal(b''.join(struct.pack('<H', n) for n in entries)),
                    '  let at = i32.toUsize(index) * 2',
                    '  return u8.toI32(data[at]) + u8.toI32(data[at + 1]) * 256', '}', ''])
    ints('tzAliasCanonicalId', [int(a[1]) for a in aliases])
    ints('tzTransitionCount', [int(z[2]) for z in zones])
    flattened = []
    starts = []
    for _, name, count in zones:
        assert len(transitions[name]) == int(count), name
        starts.append(len(flattened))
        flattened.extend(transitions[name])
    ints('transitionBase', starts)
    for fn, field, result in [('tzTransitionStart', 0, 'i64'), ('tzTransitionOffset', 1, 'i32')]:
        out.extend([f'pub fn {fn}(id: i32, index: i32) -> {result} {{',
                    '  let data = ' + literal(b''.join(struct.pack('<q', t[field]) for t in flattened)),
                    '  let value = readSigned64(data, i32.toUsize(transitionBase(id) + index) * 8)'])
        out.append('  return ' + ('value' if result == 'i64' else 'i64.toI32(value)'))
        out.extend(['}', ''])
    return '\n'.join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('reference', type=pathlib.Path, help='Pinned QuickJS checkout')
    parser.add_argument('--output', type=pathlib.Path, default=pathlib.Path('src/temporal_timezone_data.silk'))
    args = parser.parse_args()
    args.output.write_text(generate(args.reference / 'temporal/tzdata_generated.c'))


if __name__ == '__main__':
    main()
