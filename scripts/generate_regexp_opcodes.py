#!/usr/bin/env python3
"""Generate the Silk opcode numbers from the pinned QuickJS bytecode definition."""
import argparse
import hashlib
from pathlib import Path
import re

SHA256 = "2a98d646089f3a72f25480116297c5fdb5b28fd9f815447273951f4ade4a115e"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('header', type=Path)
    parser.add_argument('--output', type=Path, default=Path(__file__).resolve().parents[1] / 'src/regexp_opcodes.silk')
    args = parser.parse_args()
    raw = args.header.read_bytes()
    if hashlib.sha256(raw).hexdigest() != SHA256:
        raise SystemExit('Wrong upstream opcode definition')
    entries = re.findall(r'^DEF\((\w+),\s*(\d+)\)', raw.decode(), re.M)
    if not entries:
        raise SystemExit('No opcode definitions')
    lines = [
        '// Generated by scripts/generate_regexp_opcodes.py; do not edit.',
        '// QuickJS 7d1c13c5d8f8c6b32893786ed35cdcebd88194d2.',
        '// Copyright (c) 2017-2018 Fabrice Bellard. See LICENSE.quickjs.',
        'import silk.num.u8', '',
    ]
    lines += [f'pub const REOP_{name}: u8 = {i}' for i, (name, size) in enumerate(entries)]
    lines += [f'pub const REOP_COUNT: usize = {len(entries)}', '',
              'pub const RE_HEADER_FLAGS: usize = 0',
              'pub const RE_HEADER_CAPTURE_COUNT: usize = 2',
              'pub const RE_HEADER_REGISTER_COUNT: usize = 3',
              'pub const RE_HEADER_BYTECODE_LEN: usize = 4',
              'pub const RE_HEADER_LEN: usize = 8',
              'pub const CAPTURE_COUNT_MAX: usize = 255',
              'pub const REGISTER_COUNT_MAX: usize = 255', '',
              'pub fn opcodeSize(opcode: u8) -> usize {',
              '  let sizes = b"' + ''.join(f'\\x{int(size):02x}' for name, size in entries) + '"',
              '  return u8.toUsize(sizes[u8.toUsize(opcode)])', '}', '']
    args.output.write_text('\n'.join(lines))
    print(f'Generated {len(entries)} opcodes in {args.output}')


if __name__ == '__main__':
    main()
