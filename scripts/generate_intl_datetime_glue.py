#!/usr/bin/env python3
"""Compile CLDR date-time glue patterns into src/intl_datetime_glue_data.silk.

The input is the unpacked `cldr-dates-full` npm package (its `package/` directory). Each locale
gets the Gregorian `dateTimeFormats-atTime` pattern of each length (full, long, medium, short),
or the plain `dateTimeFormats` one where CLDR has no atTime form; ICU joins a date and a time
the same way. Rerun it when CLDR is updated:

    python3 scripts/generate_intl_datetime_glue.py path/to/cldr-dates-full/package
"""
import argparse
import hashlib
import json
from pathlib import Path

LENGTHS = ['full', 'long', 'medium', 'short']


def literal(data):
    return 'b"' + ''.join(f'\\x{byte:02x}' for byte in data) + '"'


def generate(package):
    main = package / 'main'
    version = json.loads((package / 'package.json').read_text())['version']
    locales = sorted(path.name for path in main.iterdir() if (path / 'ca-gregorian.json').is_file())
    digest = hashlib.sha256()
    pool = bytearray()
    strings = {}
    table = bytearray()
    for locale in locales:
        source = (main / locale / 'ca-gregorian.json').read_bytes()
        digest.update(source)
        gregorian = json.loads(source)['main'][locale]['dates']['calendars']['gregorian']
        atTime = gregorian.get('dateTimeFormats-atTime', {}).get('standard', {})
        for length in LENGTHS:
            pattern = atTime.get(length) or gregorian['dateTimeFormats'][length]
            if pattern not in strings:
                strings[pattern] = len(pool)
                pool.extend(pattern.encode() + b'\0')
            table += strings[pattern].to_bytes(2, 'little')
    if len(pool) >= 0xFFFF:
        raise ValueError('glue data outgrew 16-bit offsets')
    lines = [
        '// Generated by scripts/generate_intl_datetime_glue.py; do not edit.',
        f'// CLDR {version} (cldr-dates-full npm package): main/*/ca-gregorian.json.',
        f'// Source SHA-256 (files concatenated in locale order): {digest.hexdigest()}',
        '// CLDR data: Unicode License V3, https://www.unicode.org/license.txt',
        '//! Tables read by `intl_datetime_glue`.',
        '',
        f'pub const CLDR_VERSION: string = "{version}"',
        f'pub const LOCALE_COUNT: usize = {len(locales)}',
        '/// Locale identifiers in CLDR spelling, sorted, NUL-separated.',
        "pub fn locales() -> &'static [u8] {",
        '  return ' + literal('\0'.join(locales).encode()),
        '}',
        '/// Four little-endian u16 offsets into `strings()` per locale: full, long, medium, short.',
        "pub fn table() -> &'static [u8] {",
        '  return ' + literal(table),
        '}',
        '/// UTF-8 patterns, NUL-terminated.',
        "pub fn strings() -> &'static [u8] {",
        '  return ' + literal(pool),
        '}',
        '',
    ]
    return '\n'.join(lines)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('package', type=Path, help='the cldr-dates-full npm package directory')
    parser.add_argument('--output', type=Path, default=Path(__file__).resolve().parents[1] / 'src/intl_datetime_glue_data.silk')
    args = parser.parse_args()
    args.output.write_text(generate(args.package))
