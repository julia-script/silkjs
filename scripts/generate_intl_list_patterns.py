#!/usr/bin/env python3
"""Compile CLDR list patterns into src/intl_list_data.silk.

The input is the unpacked `cldr-misc-full` npm package (its `package/` directory). Every CLDR
list pattern starts with `{0}`, so a pattern is stored as the text between `{0}` and `{1}` and
the text after `{1}`. Rerun it when CLDR is updated:

    python3 scripts/generate_intl_list_patterns.py path/to/cldr-misc-full/package
"""
import argparse
import hashlib
import json
from pathlib import Path

# Intl.ListFormat type x style, in the order src/intl_list.silk indexes them.
KEYS = ['standard', 'standard-short', 'standard-narrow', 'or', 'or-short', 'or-narrow', 'unit', 'unit-short', 'unit-narrow']
PARTS = ['start', 'middle', 'end', '2']
NONE = 0xFFFF


def literal(data):
    return 'b"' + ''.join(f'\\x{byte:02x}' for byte in data) + '"'


def split(pattern):
    if not pattern.startswith('{0}') or pattern.count('{0}') != 1 or pattern.count('{1}') != 1:
        raise ValueError(f'unsupported list pattern: {pattern!r}')
    between, _, suffix = pattern[3:].partition('{1}')
    return between, suffix


def generate(package):
    main = package / 'main'
    version = json.loads((package / 'package.json').read_text())['version']
    locales = sorted(path.name for path in main.iterdir() if (path / 'listPatterns.json').is_file())
    digest = hashlib.sha256()
    pool = bytearray()
    strings = {}

    def text(value):
        if value not in strings:
            strings[value] = len(pool)
            pool.extend(value.encode() + b'\0')
        return strings[value]

    sets = bytearray()
    setIndex = {}
    table = bytearray()
    for locale in locales:
        source = (main / locale / 'listPatterns.json').read_bytes()
        digest.update(source)
        patterns = json.loads(source)['main'][locale]['listPatterns']
        for key in KEYS:
            entry = bytearray()
            for part in PARTS:
                for piece in split(patterns[f'listPattern-type-{key}'][part]):
                    entry += text(piece).to_bytes(2, 'little')
            entry = bytes(entry)
            if entry not in setIndex:
                setIndex[entry] = len(sets) // len(entry)
                sets.extend(entry)
            table += setIndex[entry].to_bytes(2, 'little')
    if len(pool) >= NONE or len(setIndex) >= NONE:
        raise ValueError('list data outgrew 16-bit offsets')
    names = '\0'.join(locales).encode()
    lines = [
        '// Generated by scripts/generate_intl_list_patterns.py; do not edit.',
        f'// CLDR {version} (cldr-misc-full npm package): main/*/listPatterns.json.',
        f'// Source SHA-256 (files concatenated in locale order): {digest.hexdigest()}',
        '// CLDR data: Unicode License V3, https://www.unicode.org/license.txt',
        '//! Tables read by `intl_list`.',
        '',
        f'pub const CLDR_VERSION: string = "{version}"',
        f'pub const LOCALE_COUNT: usize = {len(locales)}',
        '/// Locale identifiers in CLDR spelling, sorted, NUL-separated.',
        "pub fn locales() -> &'static [u8] {",
        '  return ' + literal(names),
        '}',
        '/// Nine little-endian u16 pattern set indices per locale: conjunction, disjunction and',
        '/// unit, each long, short and narrow.',
        "pub fn table() -> &'static [u8] {",
        '  return ' + literal(table),
        '}',
        '/// Pattern sets: start, middle, end and pair, each a u16 offset of the text between the',
        '/// two elements and of the text after the second, into `strings()`.',
        "pub fn sets() -> &'static [u8] {",
        '  return ' + literal(sets),
        '}',
        '/// UTF-8 texts, NUL-terminated.',
        "pub fn strings() -> &'static [u8] {",
        '  return ' + literal(pool),
        '}',
        '',
    ]
    return '\n'.join(lines)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('package', type=Path, help='the cldr-misc-full npm package directory')
    parser.add_argument('--output', type=Path, default=Path(__file__).resolve().parents[1] / 'src/intl_list_data.silk')
    args = parser.parse_args()
    args.output.write_text(generate(args.package))
