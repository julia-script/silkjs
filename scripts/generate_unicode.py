#!/usr/bin/env python3
"""Translate the pinned QuickJS Unicode data, not its executable C code.

Usage: python3 scripts/generate_unicode.py /path/to/quickjs/libunicode-table.h
The generated Silk module is checked in; Python and C are not runtime dependencies.
"""
import argparse
import ast
import hashlib
import re
from pathlib import Path

REVISION = "7d1c13c5d8f8c6b32893786ed35cdcebd88194d2"
TABLE_SHA256 = "7fb4fbeffc7bc3e12c837ce602cd9f5a7e9e2b06a9bba95e23d61cdb8b6bc409"


def byte_literal(data):
    return 'b"' + ''.join(f'\\x{byte:02x}' for byte in data) + '"'


def generate(source):
    if hashlib.sha256(source).hexdigest() != TABLE_SHA256:
        raise ValueError("Unicode source does not match the pinned QuickJS revision")
    text = re.sub(r'/\*.*?\*/|//[^\n]*', '', source.decode('ascii'), flags=re.S)
    out = [
        '// Generated by scripts/generate_unicode.py; do not edit.',
        f'// QuickJS {REVISION}; Unicode 17.0.0.',
        '// Copyright (c) 2017-2018 Fabrice Bellard. See LICENSE.quickjs.',
        'import silk.num.u8', 'import silk.num.u32', '',
    ]
    arrays = {}
    for width, name, declared, body in re.findall(
        r'static const uint(8|16|32)_t\s+(\w+)\[(\d*)\]\s*=\s*\{(.*?)\};', text, re.S
    ):
        values = []
        for token in body.split(','):
            token = token.strip()
            if not token:
                continue
            count = re.fullmatch(r'countof\((\w+)\)', token)
            values.append(len(arrays[count[1]]) if count else int(token, 0))
        if declared and len(values) != int(declared):
            raise ValueError(f"Incorrect table length: {name}")
        arrays[name] = values
        width = int(width) // 8
        data = b''.join(value.to_bytes(width, 'little') for value in values)
        out.append(f'pub const {name}_len: usize = {len(values)}')
        if width == 1:
            out.extend([f"pub fn {name}() -> &'static [u8] {{", f'  return {byte_literal(data)}', '}'])
        else:
            out.extend([f'pub fn {name}(index: usize) -> u32 {{',
                        f'  let data = {byte_literal(data)}',
                        f'  let at = index * {width}'])
            terms = ['u8.toU32(data[at])']
            terms.extend(f'u32.shiftLeft(u8.toU32(data[at + {i}]), {8*i})' for i in range(1, width))
            out.extend(['  return ' + ' | '.join(terms), '}'])
        out.append('')
    for name, body in re.findall(r'static const char\s+(\w+)\[\]\s*=\s*(.*?);', text, re.S):
        strings = re.findall(r'"(?:[^"\\]|\\.)*"', body)
        data = ''.join(ast.literal_eval(s) for s in strings).encode('ascii') + b'\x00'
        out.extend([f"pub fn {name}() -> &'static [u8] {{", f'  return {byte_literal(data)}', '}', ''])
    for body in re.findall(r'typedef enum\s*\{(.*?)\}\s*\w+;', text, re.S):
        for value, name in enumerate(filter(None, (part.strip() for part in body.split(',')))):
            if not re.fullmatch(r'\w+', name):
                raise ValueError(f"Unsupported enum initializer: {name}")
            out.append(f'pub const {name}: u32 = {value}')
        out.append('')
    body = re.search(r'static const uint8_t \* const unicode_prop_table\[\]\s*=\s*\{(.*?)\};', text, re.S)
    if body is None:
        raise ValueError('Missing property dispatch table')
    names = [part.strip() for part in body[1].split(',') if part.strip()]
    out.extend([f'pub const unicode_prop_table_len: usize = {len(names)}',
                "pub fn unicode_prop_table(index: usize) -> &'static [u8] {", '  return match index {'])
    out.extend(f'    {index} => {name}()' for index, name in enumerate(names))
    # The array contract traps on an invalid index, rather than inventing an empty table.
    out.extend(['    _ => invalidPropertyIndex()', '  }', '}', '',
                "fn invalidPropertyIndex() -> &'static [u8] {",
                '  return Intrinsic.trap("QuickJS invariant violated")', '}', ''])
    return '\n'.join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('header', type=Path)
    parser.add_argument('--output', type=Path, default=Path(__file__).resolve().parents[1] / 'src/unicode_data.silk')
    args = parser.parse_args()
    output = generate(args.header.read_bytes())
    args.output.write_text(output)
    print(f'Generated {args.output} from QuickJS {REVISION}')


if __name__ == '__main__':
    main()
