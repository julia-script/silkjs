let count = 0;
const encode = value => JSON.stringify(value, (_, item) => typeof item === 'bigint' ? {$bigint:String(item)} : item);
function equal(actual, expected, label) {
    count++;
    if (encode(actual) !== encode(expected))
        throw Error(label + ': ' + encode(actual) + ' != ' + encode(expected));
}
function raises(fn, name, label) {
    let caught;
    try { fn(); } catch (e) { caught = e.name; }
    equal(caught, name, label);
}
