#!/usr/bin/env python3
"""Compile CLDR plural rules and plural ranges into src/intl_plural_data.silk.

The input is the unpacked `cldr-core` npm package (its `package/` directory). The output holds
every cardinal and ordinal rule set and every plural range table, as byte tables that
src/intl_plural.silk evaluates. Rerun it when CLDR is updated:

    python3 scripts/generate_intl_plurals.py path/to/cldr-core/package
"""
import argparse
import hashlib
import json
from pathlib import Path
import re

CATEGORIES = ['zero', 'one', 'two', 'few', 'many', 'other']
OPERANDS = {'n': 0, 'i': 1, 'v': 2, 'w': 3, 'f': 4, 't': 5, 'c': 6, 'e': 6}
# Operands are evaluated modulo 10^18 once they outgrow u64 precision; every modulus must divide it.
LIMB = 10 ** 18


def u32(value):
    if not 0 <= value < 2 ** 32:
        raise ValueError(f'plural rule value out of range: {value}')
    return value.to_bytes(4, 'little')


def relation(text):
    match = re.fullmatch(r'\s*([nivwftce])\s*(?:%\s*(\d+))?\s*(!=|=)\s*([\d.,\s]+?)\s*', text)
    if not match:
        raise ValueError(f'unsupported plural relation: {text!r}')
    operand, modulus, operator, values = match.groups()
    modulus = int(modulus or 0)
    if modulus and LIMB % modulus:
        raise ValueError(f'modulus {modulus} does not divide 10^18')
    ranges = []
    for item in values.split(','):
        low, _, high = item.strip().partition('..')
        ranges.append((int(low), int(high or low)))
    encoded = bytes([OPERANDS[operand]]) + u32(modulus) + bytes([operator == '!=', len(ranges)])
    return encoded + b''.join(u32(low) + u32(high) for low, high in ranges)


def condition(text):
    alternatives = [part for part in text.split(' or ')]
    out = bytes([len(alternatives)])
    for alternative in alternatives:
        relations = alternative.split(' and ')
        out += bytes([len(relations)]) + b''.join(relation(item) for item in relations)
    return out


def ruleset(rules):
    compiled = []
    for key, value in rules.items():
        category = key.removeprefix('pluralRule-count-')
        text = value.split('@')[0].strip()
        if category == 'other':
            if text:
                raise ValueError('the other category must have no condition')
            continue
        compiled.append(bytes([CATEGORIES.index(category)]) + condition(text))
    compiled.sort(key=lambda item: item[0])
    return bytes([len(compiled)]) + b''.join(compiled)


def ranges(table):
    triples = []
    for key, value in table.items():
        match = re.fullmatch(r'pluralRange-start-(\w+)-end-(\w+)', key)
        triples.append((CATEGORIES.index(match[1]), CATEGORIES.index(match[2]), CATEGORIES.index(value)))
    triples.sort()
    return bytes([len(triples)]) + b''.join(bytes(t) for t in triples)


def literal(data):
    return 'b"' + ''.join(f'\\x{byte:02x}' for byte in data) + '"'


def generate(package):
    supplemental = package / 'supplemental'
    sources = {name: (supplemental / name).read_bytes() for name in ['plurals.json', 'ordinals.json', 'pluralRanges.json']}
    version = json.loads((package / 'package.json').read_text())['version']
    cardinal = json.loads(sources['plurals.json'])['supplemental']['plurals-type-cardinal']
    ordinal = json.loads(sources['ordinals.json'])['supplemental']['plurals-type-ordinal']
    rangeData = json.loads(sources['pluralRanges.json'])['supplemental']['plurals']
    locales = sorted(set(cardinal) | set(ordinal) | set(rangeData) - {'root'})
    blob = bytearray()
    offsets = {}

    def intern(data):
        if data not in offsets:
            offsets[data] = len(blob)
            blob.extend(data)
        return offsets[data]

    NONE = 0xFFFF
    table = bytearray()
    for locale in locales:
        for source, compile in [(cardinal, ruleset), (ordinal, ruleset), (rangeData, ranges)]:
            offset = NONE
            if locale in source:
                offset = intern(compile(source[locale]))
                if offset >= NONE:
                    raise ValueError('plural data outgrew 16-bit offsets')
            table += offset.to_bytes(2, 'little')
    names = '\0'.join(locales).encode()
    digest = hashlib.sha256(b''.join(sources[name] for name in sorted(sources))).hexdigest()
    lines = [
        '// Generated by scripts/generate_intl_plurals.py; do not edit.',
        f'// CLDR {version} (cldr-core npm package): plurals.json, ordinals.json, pluralRanges.json.',
        f'// Source SHA-256 (concatenated in that name order): {digest}',
        '// CLDR data: Unicode License V3, https://www.unicode.org/license.txt',
        '//! Tables evaluated by `intl_plural`. Each locale has three 16-bit offsets into `rules()`',
        '//! (cardinal, ordinal, ranges), `NONE` when CLDR has no data for it.',
        '',
        f'pub const CLDR_VERSION: string = "{version}"',
        f'pub const LOCALE_COUNT: usize = {len(locales)}',
        f'pub const NONE: usize = {NONE}',
        '/// Locale identifiers in CLDR spelling, sorted, NUL-separated.',
        "pub fn locales() -> &'static [u8] {",
        '  return ' + literal(names),
        '}',
        '/// Three little-endian u16 offsets per locale, in `locales()` order.',
        "pub fn offsets() -> &'static [u8] {",
        '  return ' + literal(table),
        '}',
        '/// Rule sets: count, then per rule a category, its alternatives, their relations',
        '/// (operand, u32 modulus, negated, range count, u32 ranges). Range tables: count, then',
        '/// (start, end, result) category triples.',
        "pub fn rules() -> &'static [u8] {",
        '  return ' + literal(blob),
        '}',
        '',
    ]
    return '\n'.join(lines)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('package', type=Path, help='the cldr-core npm package directory')
    parser.add_argument('--output', type=Path, default=Path(__file__).resolve().parents[1] / 'src/intl_plural_data.silk')
    args = parser.parse_args()
    args.output.write_text(generate(args.package))
